import { useState, type FormEvent } from 'react';
import { useRag } from '../hooks/useRag';
import { useRetrieval } from '../hooks/useRetrieval';
import { cx } from '../lib/cx';
import styles from '../styles.module.css';
import { DocumentsPanel } from './DocumentsPanel';

export function RagView() {
  const {
    stored,
    storedError,
    selectedIds,
    toggle,
    uploadStatus,
    uploadResult,
    uploadError,
    upload,
  } = useRetrieval();

  const rag = useRag();
  const [question, setQuestion] = useState('');

  const submit = (e: FormEvent): void => {
    e.preventDefault();
    void rag.ask(question, selectedIds);
  };

  const busy = rag.status === 'thinking' || rag.status === 'streaming';

  return (
    <div className={styles.layout}>
      <DocumentsPanel
        stored={stored}
        storedError={storedError}
        selectedIds={selectedIds}
        onToggle={toggle}
        uploadStatus={uploadStatus}
        uploadResult={uploadResult}
        uploadError={uploadError}
        onUpload={upload}
        hint="Select documents to ground the answer on (optional)."
      />

      <section className={cx(styles.panel, styles.chat)} aria-labelledby="rag-heading">
        <div className={styles['rag-head']}>
          <h2 id="rag-heading">Grounded answer</h2>
          {rag.mock !== null && (
            <span
              className={rag.mock ? styles['mock-badge'] : styles['real-badge']}
              title={
                rag.mock
                  ? 'Answer produced by the deterministic mock, not a real model.'
                  : `Answer produced by ${rag.model} (a base model — NOT fine-tuned).`
              }
            >
              {rag.mock ? 'MOCK INFERENCE' : `REAL: ${rag.model}`}
            </span>
          )}
        </div>
        <p className={styles['evidence-disclaimer']}>
          The answer below is <strong>generated by a language model</strong> grounded in
          retrieved evidence. The model is <strong>not fine-tuned</strong>. Always check
          the cited sources — a valid citation confirms the reference exists, not that it
          proves the claim.
        </p>

        <form className={styles.composer} onSubmit={submit}>
          <label htmlFor="rag-input" className="sr-only">
            Question
          </label>
          <input
            id="rag-input"
            type="text"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            placeholder="e.g. What was total revenue in FY2023?"
            disabled={busy}
          />
          <button type="submit" disabled={!question.trim() || busy}>
            {rag.status === 'thinking'
              ? 'Verifying…'
              : rag.status === 'streaming'
                ? 'Answering…'
                : 'Ask'}
          </button>
        </form>

        {rag.status === 'thinking' && (
          <p role="status" className={styles.hint}>
            Retrieving evidence and verifying citations before showing the answer…
          </p>
        )}

        {rag.status === 'error' && (
          <p role="alert" className={cx(styles.banner, styles['banner-error'])}>
            {rag.error}
          </p>
        )}

        {rag.abstained && rag.status === 'done' && (
          <div role="status" className={cx(styles.banner, styles['banner-abstain'])}>
            The assistant abstained: the selected documents don’t contain enough evidence
            to answer this question.
          </div>
        )}

        {!rag.abstained && rag.answer && (
          <article className={styles['rag-answer']}>
            <span className={styles['rag-answer-label']}>Generated answer</span>
            <div className={styles['rag-answer-text']}>{rag.answer}</div>
            {rag.invalidCitationCount > 0 && (
              <p className={cx(styles.hint, styles.warn)}>
                {rag.invalidCitationCount} fabricated citation reference(s) were detected
                and removed.
              </p>
            )}
          </article>
        )}

        {rag.citations.length > 0 && (
          <div className={styles.passages}>
            <p className={styles.hint}>
              Sources (cited evidence — verbatim from documents)
            </p>
            {rag.citations.map((c) => (
              <article
                key={c.chunkId ?? `${c.documentId}-${c.page}`}
                className={styles.passage}
              >
                <header className={styles['passage-head']}>
                  <button
                    type="button"
                    className={styles['citation-link']}
                    title={
                      c.chunkId
                        ? `${c.documentTitle} — page ${c.page}, characters ${c.charStart}–${c.charEnd}`
                        : `${c.documentTitle} — page ${c.page}`
                    }
                  >
                    {c.marker ? `[${c.marker}] ` : ''}
                    {c.documentTitle}, p.{c.page}
                  </button>
                </header>
                <blockquote className={styles['passage-text']}>{c.snippet}</blockquote>
              </article>
            ))}
          </div>
        )}
      </section>
    </div>
  );
}
