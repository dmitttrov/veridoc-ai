import { useState, type FormEvent } from 'react';
import { useRag, type RagTurn } from '../hooks/useRag';
import { useRetrieval } from '../hooks/useRetrieval';
import { cx } from '../lib/cx';
import styles from '../styles.module.css';
import { DocumentsPanel } from './DocumentsPanel';

function TurnCitations({ turn }: { turn: RagTurn }) {
  if (turn.citations.length === 0) return null;
  return (
    <div className={styles.passages}>
      <p className={styles.hint}>Sources (cited evidence — verbatim from documents)</p>
      {turn.citations.map((c) => (
        <article
          key={c.chunkId ?? `${c.documentId}-${c.page}`}
          className={styles.passage}
        >
          <header className={styles['passage-head']}>
            <button
              type="button"
              className={styles['citation-link']}
              title={
                c.chunkId
                  ? `${c.documentTitle} — page ${c.page}, characters ${c.charStart}–${c.charEnd}`
                  : `${c.documentTitle} — page ${c.page}`
              }
            >
              {c.marker ? `[${c.marker}] ` : ''}
              {c.documentTitle}, p.{c.page}
            </button>
          </header>
          <blockquote className={styles['passage-text']}>{c.snippet}</blockquote>
        </article>
      ))}
    </div>
  );
}

function Turn({ turn }: { turn: RagTurn }) {
  return (
    <>
      <article className={cx(styles.message, styles['message-user'])}>
        <span className={styles['message-role']}>You</span>
        <div className={styles['message-content']}>{turn.question}</div>
      </article>

      {turn.status === 'thinking' && (
        <p role="status" className={styles.hint}>
          Retrieving evidence and verifying citations before showing the answer…
        </p>
      )}

      {turn.status === 'error' && (
        <p role="alert" className={cx(styles.banner, styles['banner-error'])}>
          {turn.error}
        </p>
      )}

      {turn.abstained && turn.status === 'done' && (
        <div role="status" className={cx(styles.banner, styles['banner-abstain'])}>
          The assistant abstained: the selected documents don’t contain enough evidence to
          answer this question.
        </div>
      )}

      {!turn.abstained && turn.answer && (
        <article className={styles['rag-answer']}>
          <span className={styles['rag-answer-label']}>Generated answer</span>
          <div className={styles['rag-answer-text']}>{turn.answer}</div>
          {turn.invalidCitationCount > 0 && (
            <p className={cx(styles.hint, styles.warn)}>
              {turn.invalidCitationCount} fabricated citation reference(s) were detected
              and removed.
            </p>
          )}
        </article>
      )}

      {turn.status === 'done' && <TurnCitations turn={turn} />}
    </>
  );
}

export function RagView() {
  const {
    stored,
    storedError,
    selectedIds,
    toggle,
    uploadStatus,
    uploadResult,
    uploadError,
    upload,
  } = useRetrieval();

  const rag = useRag();
  const [question, setQuestion] = useState('');

  const busy = rag.status === 'thinking' || rag.status === 'streaming';

  const submit = (e: FormEvent): void => {
    e.preventDefault();
    const trimmed = question.trim();
    if (!trimmed || busy) return;
    void rag.ask(trimmed, selectedIds);
    setQuestion('');
  };

  return (
    <div className={styles.layout}>
      <DocumentsPanel
        stored={stored}
        storedError={storedError}
        selectedIds={selectedIds}
        onToggle={toggle}
        uploadStatus={uploadStatus}
        uploadResult={uploadResult}
        uploadError={uploadError}
        onUpload={upload}
        hint="Select documents to ground the answers on (optional)."
      />

      <section className={cx(styles.panel, styles.chat)} aria-labelledby="rag-heading">
        <div className={styles['rag-head']}>
          <h2 id="rag-heading">Grounded conversation</h2>
          {rag.mock !== null && (
            <span
              className={rag.mock ? styles['mock-badge'] : styles['real-badge']}
              title={
                rag.mock
                  ? 'Answers produced by the deterministic mock, not a real model.'
                  : `Answers produced by ${rag.model} (a base model — NOT fine-tuned).`
              }
            >
              {rag.mock ? 'MOCK INFERENCE' : `REAL: ${rag.model}`}
            </span>
          )}
        </div>
        <p className={styles['evidence-disclaimer']}>
          Answers below are <strong>generated by a language model</strong> grounded in
          retrieved evidence; follow-up questions use the conversation for context but are
          never answered from it. The model is <strong>not fine-tuned</strong>. Always
          check the cited sources — a valid citation confirms the reference exists, not
          that it proves the claim.
        </p>

        <div
          className={styles.messages}
          role="log"
          aria-live="polite"
          aria-relevant="additions text"
        >
          {rag.turns.length === 0 && (
            <p className={styles.hint}>
              Ask a question about the selected documents; follow-ups keep the
              conversation’s context.
            </p>
          )}
          {rag.turns.map((turn) => (
            <Turn key={turn.id} turn={turn} />
          ))}
        </div>

        <form className={styles.composer} onSubmit={submit}>
          <label htmlFor="rag-input" className="sr-only">
            Question
          </label>
          <input
            id="rag-input"
            type="text"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            placeholder={
              rag.turns.length === 0
                ? 'e.g. What was total revenue in FY2023?'
                : 'Ask a follow-up…'
            }
            disabled={busy}
          />
          <button type="submit" disabled={!question.trim() || busy}>
            {rag.status === 'thinking'
              ? 'Verifying…'
              : rag.status === 'streaming'
                ? 'Answering…'
                : 'Ask'}
          </button>
          {rag.turns.length > 0 && !busy && (
            <button type="button" className={styles.secondary} onClick={rag.reset}>
              New conversation
            </button>
          )}
        </form>
      </section>
    </div>
  );
}
